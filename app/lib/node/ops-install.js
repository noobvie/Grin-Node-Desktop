'use strict';
/**
 * Fresh node install for one network (Script 01 parity, Windows column):
 *
 *   refuse when the network is already installed, or when chain data was
 *   asked for and a chain_data folder is already there (assertInstallable:
 *   replacing either is Reinstall's job, behind its typed confirmation)
 *   → disk gate (25 GiB full / 10 GiB pruned on INSTALL_ROOT's volume)
 *   → a node that is up (stray process or leftover service) is stopped
 *   → store binaries present (grin, nssm; each skipped when already there)
 *   → <nodeDir>\grin.exe copied from the store (module-layout.md §3)
 *   → grin-server.toml generated by grin itself + patched, secrets restored
 *   → chain data (optional: "skip chain data" = slow sync from genesis)
 *   → NSSM service registered → nodes.json → start → fresh scan row.
 *
 * <nodeDir>\.install-incomplete exists from the first write to the dir
 * until the service is registered. While it is there the network scans as
 * not installed, so a failed or interrupted install is completed by running
 * Install again (which may then replace its own leftover chain_data).
 *
 * Progress is reported twice: as SSE 'node-install' events {network, mode,
 * phase} for the UI and through the optional onPhase callback for the job
 * runner. The terminal 'done' / 'failed' go to 'node-install' only: on the
 * 'job' stream those two names belong to the job runner.
 */

const fs       = require('fs');
const path     = require('path');
const paths    = require('../util/paths');
const log      = require('../util/log');
const sse      = require('../util/sse');
const { GIB }  = require('../util/disk');
const catalog  = require('../services/catalog');
const fields   = require('./scan-fields');
const registry = require('./registry');

const SCOPE = 'node.install';
const DISK_GATE_BYTES = { full: 25 * GIB, pruned: 10 * GIB };

const _deps = {
    requireFree: null, binaries: null, generateNodeConfig: null, downloadChainData: null,
    lifecycle: null, scanNetwork: null,
};
const real = {
    requireFree:        () => require('../util/disk').requireFree,
    binaries:           () => require('../installer/binaries'),
    generateNodeConfig: () => require('../installer/node-config').generateNodeConfig,
    downloadChainData:  () => require('../installer/chaindata').downloadChainData,
    lifecycle:          () => require('./ops-lifecycle'),
    scanNetwork:        () => require('./scan').scanNetwork,
};
const dep = k => _deps[k] || real[k]();

function validate({ network, mode, startType, chainData }) {
    if (!catalog.NETWORKS.includes(network)) throw new Error(`unknown network "${network}"`);
    if (!catalog.MODES.includes(mode)) throw new Error(`unknown mode "${mode}"`);
    if (network === 'testnet' && mode === 'full') throw new Error('testnet has no full-archive mode');
    if (!['auto', 'demand', 'disabled'].includes(startType)) throw new Error(`unknown startType "${startType}"`);
    if (typeof chainData !== 'boolean') throw new Error('chainData must be a boolean');
}

/**
 * Throws an error with `status = 409` when installing would silently
 * replace something: an installed node, or (with chainData) an existing
 * chain_data folder.
 */
function assertInstallable({ network, chainData }) {
    const { dir } = fields.nodeFiles(network);
    const unfinished = fields.incomplete(network);
    let msg = null;
    if (fields.isInstalled(network)) {
        msg = `${network} is already installed in ${dir}; use Reinstall to replace it`;
    } else if (!chainData && unfinished === 'chain-data') {
        msg = `${path.join(dir, 'chain_data')} is a partial extraction; install with chain data to replace it`;
    } else if (chainData && !unfinished && fs.existsSync(path.join(dir, 'chain_data'))) {
        // After an unfinished install the folder is that install's own leftover.
        msg = `${path.join(dir, 'chain_data')} already exists and downloading chain data would replace it; ` +
              'install without chain data to keep it, or use Reinstall';
    }
    if (!msg) return;
    const err = new Error(msg);
    err.status = 409;
    err.code = 'NODE_EXISTS';
    throw err;
}

/**
 * @param {{network:string, mode:string, startType?:string, chainData?:boolean, onPhase?:Function}} opts
 * @returns {Promise<object>} the NodeRow after the install
 */
async function installNode({ network, mode, startType = 'auto', chainData = true, onPhase } = {}) {
    validate({ network, mode, startType, chainData });
    assertInstallable({ network, chainData });

    const announce = (name, extra = {}) => sse.emit('node-install', { network, mode, phase: name, ...extra });
    const phase = name => {
        announce(name);
        if (typeof onPhase === 'function') { try { onPhase(name); } catch (_) { /* UI only */ } }
    };

    const { dir } = fields.nodeFiles(network);
    try {
        phase('disk-check');
        await dep('requireFree')(paths.INSTALL_ROOT, DISK_GATE_BYTES[mode], `install ${network} ${mode}`);

        const lifecycle = dep('lifecycle');
        phase('stop');
        const stop = await lifecycle.stopAndConfirm(network);
        if (!stop.ok) throw new Error(`${network}: cannot install over a node that is still up: ${stop.detail}`);

        phase('binaries');
        const binaries = dep('binaries');
        const store = await binaries.installGrin();
        await binaries.installNssm();

        phase('copy-binary');
        fs.mkdirSync(dir, { recursive: true });
        if (fs.existsSync(fields.installMarker(network))) {
            // Completing an unfinished install: its exe is not a version to roll back to.
            fs.rmSync(fields.nodeFiles(network).exe, { force: true });
        }
        fs.writeFileSync(fields.installMarker(network), `${new Date().toISOString()}\n`, 'utf8');
        binaries.copyNodeBinary(network);

        phase('config');
        await dep('generateNodeConfig')({ network, mode });

        if (chainData) {
            phase('chain-data');
            await dep('downloadChainData')({ network, mode });
        } else {
            log.info(SCOPE, `${network}: chain data skipped — the node will sync from genesis`);
        }

        phase('service');
        const svc = await lifecycle.installService({ network, mode, startType });
        registry.upsertNode(network, {
            mode, dir, serviceName: svc.name, startType,
            installedAt:   new Date().toISOString(),
            binaryVersion: store && store.version ? store.version : null,
        });
        fs.rmSync(fields.installMarker(network), { force: true });

        phase('start');
        const started = await lifecycle.startNode(network);
        if (!started.ok) throw new Error(`node installed but did not start: ${started.detail}`);

        announce('done', { result: started.result });
        log.info(SCOPE, `${network} ${mode} installed`, { startType, chainData });
        return dep('scanNetwork')(network);
    } catch (e) {
        announce('failed', { error: e.message });
        log.error(SCOPE, `${network} ${mode} install failed: ${e.message}`);
        throw e;
    }
}

module.exports = { installNode, assertInstallable, validate, DISK_GATE_BYTES, _deps };
